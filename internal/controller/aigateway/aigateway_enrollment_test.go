func TestEnrollmentOptIn(t *testing.T) {
	for _, state := range []string{"", removedState, managedState} {
		for _, config := range []*componentApi.GridEnrollmentConfig{nil, {}, {Enabled: true}} {
			t.Run(fmt.Sprintf("%s/%v", state, config), func(t *testing.T) {
				g := NewWithT(t)
				obj := newTestAIGateway()
				obj.Spec.AIGrid = componentApi.AIGridComponent{ManagementState: state, GridEnrollment: config}
				rr := newTestRR(obj)
				m := newTestModule(t)
				t.Setenv(enrollmentImageEnv, "")
				t.Setenv(enrollmentDBImageEnv, "")
				err := m.renderEnrollment(context.Background(), rr)
				if state == managedState && config != nil && config.Enabled {
					g.Expect(err).To(MatchError(ContainSubstring("requires " + enrollmentImageEnv)))
				} else {
					g.Expect(err).NotTo(HaveOccurred())
					g.Expect(rr.Resources).To(BeEmpty())
				}
			})
		}
	}
}

func TestEnrollmentChart(t *testing.T) {
	g := NewWithT(t)
	path := filepath.Join("..", "..", "..", "config", "manifests", "gridenrollment")
	rendered, err := renderEnrollmentChart(path, testEnrollmentImage, testDBImage)
	g.Expect(err).NotTo(HaveOccurred())
	again, err := renderEnrollmentChart(path, testEnrollmentImage, testDBImage)
	g.Expect(err).NotTo(HaveOccurred())
	g.Expect(again).To(Equal(rendered))
	jobs, deployments, pvcs := 0, 0, 0
	var jobName string
	for _, obj := range rendered {
		g.Expect(obj.GetKind()).NotTo(Equal("Secret"), "certificate bytes must be generated by the operand")
		for key := range obj.GetAnnotations() {
			g.Expect(key).NotTo(HavePrefix("helm.sh/hook"))
		}
		switch obj.GetKind() {
		case "Job":
			jobs++
			jobName = obj.GetName()
			g.Expect(obj.Object["spec"]).NotTo(HaveKey("ttlSecondsAfterFinished"))
			var job batchv1.Job
			g.Expect(runtime.DefaultUnstructuredConverter.FromUnstructured(obj.Object, &job)).To(Succeed())
			g.Expect(job.Spec.Template.Spec.Containers[0].Image).To(Equal(testEnrollmentImage))
			g.Expect(job.Spec.Template.Spec.Containers[0].Command).To(Equal([]string{"enrollment", "bootstrap"}))
			g.Expect(job.Spec.Template.Spec.Containers[0].Args).NotTo(ContainElement("--force-regenerate"))
			g.Expect(job.Spec.Template.Spec.Containers[0].Args).To(ContainElement(enrollmentNamespace))
		case "Deployment":
			deployments++
			g.Expect(obj.GetNamespace()).To(Equal(enrollmentNamespace))
			var deployment appsv1.Deployment
			g.Expect(runtime.DefaultUnstructuredConverter.FromUnstructured(obj.Object, &deployment)).To(Succeed())
			for _, c := range append(deployment.Spec.Template.Spec.Containers, deployment.Spec.Template.Spec.InitContainers...) {
				g.Expect([]string{testEnrollmentImage, testDBImage}).To(ContainElement(c.Image))
			}
		case "PersistentVolumeClaim":
			pvcs++
			g.Expect(obj.GetOwnerReferences()).To(BeEmpty())
		case "Namespace":
			g.Expect(obj.GetName()).To(Equal(enrollmentNamespace))
			g.Expect(obj.GetOwnerReferences()).To(BeEmpty())
		}
	}
	g.Expect(jobs).To(Equal(1))
	g.Expect(deployments).To(Equal(2))
	g.Expect(pvcs).To(Equal(1))
	upgraded, err := renderEnrollmentChart(path, "quay.io/example/enrollment:v2", testDBImage)
	g.Expect(err).NotTo(HaveOccurred())
	for _, obj := range upgraded {
		if obj.GetKind() == "Job" {
			g.Expect(obj.GetName()).NotTo(Equal(jobName), "immutable Jobs need a new name on upgrade")
		}
	}
}

func TestEnrollmentReadiness(t *testing.T) {
	for _, tc := range []struct {
		name    string
		job     *batchv1.Job
		ready   bool
		message string
	}{
		{name: "missing bootstrap", message: "waiting for its bootstrap Job"},
		{name: "running bootstrap", job: &batchv1.Job{}, message: "bootstrap is running"},
		{name: "failed bootstrap", job: &batchv1.Job{Status: batchv1.JobStatus{Conditions: []batchv1.JobCondition{{Type: batchv1.JobFailed, Status: corev1.ConditionTrue}}}}, message: "bootstrap failed"},
		{name: "waiting for workloads", job: &batchv1.Job{Status: batchv1.JobStatus{Conditions: []batchv1.JobCondition{{Type: batchv1.JobComplete, Status: corev1.ConditionTrue}}}}, message: "not available"},
		{name: "ready", job: &batchv1.Job{Status: batchv1.JobStatus{Conditions: []batchv1.JobCondition{{Type: batchv1.JobComplete, Status: corev1.ConditionTrue}}}}, ready: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			g := NewWithT(t)
			scheme := newTestScheme(t)
			g.Expect(batchv1.AddToScheme(scheme)).To(Succeed())
			var objects []client.Object
			if tc.job != nil {
				tc.job.ObjectMeta = metav1.ObjectMeta{Name: "bootstrap-test", Namespace: enrollmentNamespace}
				objects = append(objects, tc.job)
			}
			if tc.ready {
				for _, name := range []string{enrollmentName, enrollmentName + "-db"} {
					objects = append(objects, &appsv1.Deployment{ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: enrollmentNamespace}, Status: appsv1.DeploymentStatus{ReadyReplicas: 1}})
				}
			}
			rr := newTestRR(newTestAIGateway())
			rr.Client = fake.NewClientBuilder().WithScheme(scheme).WithObjects(objects...).Build()
			rr.Resources = append(rr.Resources, unstructured.Unstructured{Object: map[string]any{"apiVersion": "batch/v1", "kind": "Job", "metadata": map[string]any{"name": "bootstrap-test", "namespace": enrollmentNamespace}}})
			message, err := enrollmentPending(context.Background(), rr)
			g.Expect(err).NotTo(HaveOccurred())
			if tc.message == "" {
				g.Expect(message).To(BeEmpty())
			} else {
				g.Expect(message).To(ContainSubstring(tc.message))
			}
		})
	}
}

func TestEnrollmentRetainsState(t *testing.T) {
	m := newTestModule(t)
	rr := newTestRR(newTestAIGateway())
	for _, kind := range []string{"Namespace", "Secret", "PersistentVolumeClaim"} {
		obj := unstructured.Unstructured{Object: map[string]any{"apiVersion": "v1", "kind": kind}}
		obj.SetNamespace(enrollmentNamespace)
		obj.SetName("state")
		if kind == "Namespace" {
			obj.SetNamespace("")
			obj.SetName(enrollmentNamespace)
		}
		deletable, err := m.maasAwareGCPredicate(rr, obj)
		NewWithT(t).Expect(err).NotTo(HaveOccurred())
		NewWithT(t).Expect(deletable).To(BeFalse(), kind)
	}
}
